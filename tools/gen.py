"""Generate src/generated/sheets.h: one constexpr struct per sheet row."""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "generated" / "sheets.h"


def ident(s):
    return "".join(c if c.isalnum() else "_" for c in s)


def main():
    sheets = {p.stem: json.loads(p.read_text(encoding="utf-8")) for p in sorted((ROOT / "sheets").glob("*.json"))}
    out = ["// Generated by tools/gen.py from sheets/*.json. Edit the sheets, not this file.",
           "#pragma once", "#include <cstdint>", "", "namespace gthl::sheets {", ""]

    out.append("// hooks: natives by hash (0 = not resolved yet, see preflight)")
    for r in sheets["hooks"]["rows"]:
        if r["kind"] == "native":
            out.append(f"constexpr uint64_t NATIVE_{ident(r['symbol'])} = {r['hash'] or '0'}ULL;  // {r['returns']}({', '.join(r['params'])})")
    out.append("")

    out.append("// channels")
    for r in sheets["channels"]["rows"]:
        out.append(f"constexpr uint16_t PORT_{ident(r['id']).upper()} = {r['port']};  // {r['from']} -> {r['to']}: {r['fields']}")
    out.append("")

    out.append("// rules")
    for r in sheets["rules"]["rows"]:
        out.append(f"struct {ident(r['id'])} {{  // {r['effect']}")
        for k, v in r["params"].items():
            out.append(f"    static constexpr int {k} = {v};")
        out.append("};")
    out.append("")
    out.append("}  // namespace gthl::sheets")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
